#!/usr/bin/env python3
"""Regenerate zimi/addon_wheels.py: the wheels a frozen desktop app unpacks for the Browser and Video add-ons (it has no
pip). Reads PyPI's JSON for the pinned versions and writes each wheel's URL, sha256 and size; nothing is downloaded.

    python3 scripts/pin_addon_wheels.py > zimi/addon_wheels.py
"""

import json
import urllib.request

PLAYWRIGHT = "1.64.1"
GREENLET = "3.5.6"
UNIVERSAL = (("pyee", "14.0.0"), ("typing_extensions", "4.16.0"), ("yt-dlp", "2026.10.26"))
ABIS = ("cp312", "cp313")  # the Pythons the desktop builds use (desktop-release.yml, build_local.sh)
# The standard-library modules the unpacked packages import (yt-dlp, Playwright, pyee, greenlet) that the app itself
# might not use, so PyInstaller would leave them out of a frozen app (yt-dlp died on `optparse`). Found by reading
# the wheels' imports against sys.stdlib_module_names; both desktop specs add them as hidden imports.
FROZEN_STDLIB = (
    "optparse", "fileinput", "netrc", "pty", "quopri", "getpass", "sqlite3", "secrets", "mimetypes", "calendar",
    "bisect", "heapq", "tokenize", "textwrap", "shlex", "sysconfig", "uuid", "hmac", "zipimport", "annotationlib",
    "doctest", "faulthandler", "keyword", "unittest", "http.cookiejar", "http.cookies", "http.server", "html.parser",
    "html.entities", "xml.etree.ElementTree", "concurrent.futures", "importlib.resources", "importlib.metadata",
    "email.header", "email.message", "email.utils", "asyncio", "ctypes", "ssl", "zlib",
)
# target -> (playwright wheel tag, greenlet wheel tag)
TARGET_TAGS = {
    "x64": ("manylinux1_x86_64", "manylinux_2_24_x86_64.manylinux_2_28_x86_64"),
    "arm64": ("manylinux_2_17_aarch64", "manylinux_2_24_aarch64.manylinux_2_28_aarch64"),
    "mac-x64": ("macosx_10_13_x86_64", "macosx_11_0_universal2"),
    "mac-arm64": ("macosx_11_0_arm64", "macosx_11_0_universal2"),
    "win-x64": ("win_amd64", "win_amd64"),
}


def urls(pkg, ver):
    with urllib.request.urlopen("https://pypi.org/pypi/%s/%s/json" % (pkg, ver), timeout=60) as r:
        return json.load(r)["urls"]


def pick(files, *needles):
    for f in files:
        if f["filename"].endswith(".whl") and all(n in f["filename"] for n in needles):
            return (f["url"], f["digests"]["sha256"], f["size"])
    raise SystemExit("no wheel for %s" % (needles,))


def main():
    pw, gl = urls("playwright", PLAYWRIGHT), urls("greenlet", GREENLET)
    out = {"playwright": {}, "greenlet": {}, "universal": []}
    for target, (pw_tag, gl_tag) in TARGET_TAGS.items():
        out["playwright"][target] = pick(pw, pw_tag)
        for abi in ABIS:
            out["greenlet"][(abi, target)] = pick(gl, "-%s-%s-" % (abi, abi), gl_tag)
    for pkg, ver in UNIVERSAL:
        out["universal"].append(pick(urls(pkg, ver), "py3-none-any"))
    print('"""Generated by scripts/pin_addon_wheels.py: the wheels a frozen app unpacks for its add-ons (url, sha256, bytes)."""\n')
    print("PLAYWRIGHT = %r\nGREENLET = %r\nABIS = %r\nFROZEN_STDLIB = %r\n" % (PLAYWRIGHT, GREENLET, ABIS, FROZEN_STDLIB))
    print("PLAYWRIGHT_WHEELS = {")
    for k, v in out["playwright"].items():
        print("    %r: %r," % (k, v))
    print("}\nGREENLET_WHEELS = {")
    for k, v in out["greenlet"].items():
        print("    %r: %r," % (k, v))
    print("}\n#: py3-none-any: pyee and typing_extensions (Playwright's), yt-dlp.\nUNIVERSAL_WHEELS = {")
    for (pkg, _ver), v in zip(UNIVERSAL, out["universal"]):
        print("    %r: %r," % (pkg, v))
    print("}")


if __name__ == "__main__":
    main()
